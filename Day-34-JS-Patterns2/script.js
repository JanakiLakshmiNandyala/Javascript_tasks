// 1. Print 1 to 5 in 5 rows

for (let i = 1; i <= 5; i++) {

    for (let j = 1; j <= 5; j++) {
        document.write(j + " ");
    }

    document.write("<br>");
}
document.write("<hr>");

// 2. Print row number repeatedly

for (let i = 1; i <= 5; i++) {

    for (let j = 1; j <= i; j++) {
        document.write(i + " ");
    }

    document.write("<br>");
}

document.write("<hr>");
// 3. Increasing triangle

for (let i = 1; i <= 5; i++) {

    for (let j = 1; j <= i; j++) {
        document.write(j + " ");
    }

    document.write("<br>");
}
document.write("<hr>");

// 4. Decreasing sequence

for (let i = 1; i <= 5; i++) {

    for (let j = i; j >= 1; j--) {
        document.write(j + " ");
    }

    document.write("<br>");
}
document.write("<hr>");

// 5. Print 5 to 1 in every row

